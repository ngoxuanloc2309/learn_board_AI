#!/usr/bin/env python3
"""Generates font_vi_8x16.c and font_vi_8x16.h from a GNU Unifont .hex file.

Runs on the PC, never in the firmware. Usage:
    python gen_font_vi.py path/to/unifont.hex out_dir

The glyph set is ASCII 0x20..0x7E plus every Vietnamese letter in NFC form
(12 vowels x 6 forms x 2 cases, plus d with stroke): 229 glyphs. Every glyph must be
8x16 (32 hex digits in the .hex file), otherwise the script stops.

LICENSE: the glyph bitmaps come from GNU Unifont. The owner must read the upstream
license text (unifoundry.com) and keep it next to the generated file before the
firmware is released. This script does not decide that.
"""
import sys
import unicodedata

VOWELS = "aăâeêioôơuưy"
MARKS = ["", "\u0300", "\u0301", "\u0303", "\u0309", "\u0323"]  # none, grave, acute, tilde, hook, dot below


def wanted_codepoints():
    cps = set(range(0x20, 0x7F))
    for base in VOWELS:
        for case in (str.lower, str.upper):
            for mark in MARKS:
                s = unicodedata.normalize("NFC", case(base) + mark)
                if len(s) != 1:
                    sys.exit("not a single NFC character: %r" % s)
                cps.add(ord(s))
    cps.add(ord("\u0111"))  # d with stroke
    cps.add(ord("\u0110"))  # D with stroke
    return sorted(cps)


def load_hex(path):
    table = {}
    with open(path, "r", encoding="ascii") as f:
        for line in f:
            line = line.strip()
            if not line or ":" not in line:
                continue
            code, data = line.split(":", 1)
            table[int(code, 16)] = data
    return table


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    hexpath, outdir = sys.argv[1], sys.argv[2]
    table = load_hex(hexpath)
    cps = wanted_codepoints()
    if len(cps) != 229:
        sys.exit("expected 229 code points, got %d" % len(cps))
    rows = []
    for cp in cps:
        data = table.get(cp)
        if data is None:
            sys.exit("U+%04X missing in the font" % cp)
        if len(data) != 32:
            sys.exit("U+%04X is not 8x16 (%d hex digits)" % (cp, len(data)))
        rows.append((cp, bytes.fromhex(data)))

    with open(outdir + "/font_vi_8x16.h", "w", newline="\n") as h:
        h.write("#ifndef FONT_VI_8X16_H\n#define FONT_VI_8X16_H\n\n")
        h.write("/* Generated by tools/gen_font_vi.py from GNU Unifont. Do not edit by hand. */\n")
        h.write("#include <stdint.h>\n#include <stddef.h>\n\n#ifdef __cplusplus\nextern \"C\" {\n#endif\n\n")
        h.write("#define FONT_VI_GLYPH_W      8U\n#define FONT_VI_GLYPH_H      16U\n")
        h.write("#define FONT_VI_GLYPH_COUNT  %dU\n\n" % len(rows))
        h.write("/* One glyph: code point and 16 rows, one byte per row, bit 7 is the leftmost pixel. */\n")
        h.write("typedef struct font_vi_glyph {\n    uint16_t code;\n    uint8_t  rows[16];\n} font_vi_glyph_t;\n\n")
        h.write("/* Sorted by code, so a binary search works. */\n")
        h.write("extern const font_vi_glyph_t g_font_vi_8x16[FONT_VI_GLYPH_COUNT];\n\n")
        h.write("#ifdef __cplusplus\n}\n#endif\n\n#endif /* FONT_VI_8X16_H */\n")

    with open(outdir + "/font_vi_8x16.c", "w", newline="\n") as c:
        c.write("/*\n * Generated by tools/gen_font_vi.py from GNU Unifont (8x16 glyphs). Do not edit by hand.\n")
        c.write(" * %d glyphs: ASCII 0x20..0x7E and the Vietnamese letters in NFC form.\n" % len(rows))
        c.write(" * LICENSE: see the GNU Unifont license text (unifoundry.com). The owner keeps it next to this file.\n */\n")
        c.write("#include \"font_vi_8x16.h\"\n\n")
        c.write("const font_vi_glyph_t g_font_vi_8x16[FONT_VI_GLYPH_COUNT] = {\n")
        for cp, b in rows:
            c.write("    { 0x%04X, { %s } },\n" % (cp, ", ".join("0x%02X" % x for x in b)))
        c.write("};\n")
    print("wrote %d glyphs, %d bytes of bitmap data" % (len(rows), len(rows) * 16))


if __name__ == "__main__":
    main()